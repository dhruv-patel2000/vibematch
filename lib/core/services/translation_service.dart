  Future<void> init() async {
    final prefs = await SharedPreferences.getInstance();
    currentLanguage = prefs.getString('language') ?? 'en';
    
    // Load bundled fallback first
    _loadBundledTranslations(currentLanguage);

    // Load cached remote translations if available
    final cachedStr = prefs.getString('cached_translations_$currentLanguage');
    if (cachedStr != null) {
      try {
        final Map<String, dynamic> decoded = jsonDecode(cachedStr);
        decoded.forEach((k, v) => _translations[k] = v.toString());
      } catch (_) {}
    }

    notifyListeners();

    // Fetch latest in background
    fetchTranslations();
  }

  void _loadBundledTranslations(String langCode) {
    _translations = Map<String, String>.from(_bundledTranslations[langCode] ?? _bundledTranslations['en'] ?? {});
  }

  Future<void> setLanguage(String langCode) async {
    currentLanguage = langCode;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString('language', langCode);

    _loadBundledTranslations(langCode);

    // Check cached
    final cachedStr = prefs.getString('cached_translations_$langCode');
    if (cachedStr != null) {
      try {
        final Map<String, dynamic> decoded = jsonDecode(cachedStr);
        decoded.forEach((k, v) => _translations[k] = v.toString());
      } catch (_) {}
    }

    notifyListeners();

    // Fetch and update
    await fetchTranslations();
    notifyListeners();
  }

  Future<void> fetchTranslations() async {
    try {
      final dio = Dio();
      final res = await dio.get('${AppConfig.apiBaseUrl}/languages');
      if (res.data != null && res.data['languages'] != null) {
        List langs = res.data['languages'];
        var langObj = langs.firstWhere((l) => l['code'] == currentLanguage, orElse: () => null);
        if (langObj != null && langObj['translations'] != null) {
          final Map<String, dynamic> raw = langObj['translations'];
          raw.forEach((k, v) {
            if (v != null && v.toString().isNotEmpty) {
              _translations[k] = v.toString();
            }
          });
          final prefs = await SharedPreferences.getInstance();
          await prefs.setString('cached_translations_$currentLanguage', jsonEncode(_translations));
          notifyListeners();
        }
      }
    } catch (e) {
      debugPrint('Failed to fetch remote translations: $e');
    }
  }

  String t(String key) {
    if (_translations.containsKey(key) && _translations[key]!.isNotEmpty) {
      return _translations[key]!;
    }
    // Fallback to English bundled
    if (_bundledTranslations['en']?.containsKey(key) == true) {
      return _bundledTranslations['en']![key]!;
    }
    return key;
  }
